// Command genzhkeywords 由 tsc/internal/scanner/zh_keywords.txt 生成
// tsc/internal/scanner/zh_keywords_generated.go（ChineseTypeScript 汉语关键字别名表）。
//
// 用法（在 tsc/ 目录下）：
//
//	go run ./cmd/genzhkeywords          # 重新生成
//	go run ./cmd/genzhkeywords -check   # 只校验生成物是否与词表一致（CI 用）
//
// 设计：本生成器【不信任】任何手写清单。它自己解析 scanner.go 的 textToKeyword
// 得到「英文关键字 -> ast.Kind」，再与词表比对，因此：
//
//   - 扫描器新增/删除了英文关键字而词表没跟着改  -> 生成器报错退出（不静默）
//   - 词表里写了扫描器没有的英文关键字          -> 生成器报错退出
//   - 译名重复、汉字数不在 2..6                 -> 生成器报错退出
//
// 这样「绝不靠人记得」。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"unicode"
	"unicode/utf8"
)

const (
	wordListPath = "internal/scanner/zh_keywords.txt"
	scannerPath  = "internal/scanner/scanner.go"
	outputPath   = "internal/scanner/zh_keywords_generated.go"
)

// scanner.go 里 textToKeyword 的条目长这样（含行内注释也允许）：
//
//	"abstract":    ast.KindAbstractKeyword,
var keywordEntryRe = regexp.MustCompile(`^\s*"([^"]+)":\s*ast\.Kind(\w+),\s*(?://.*)?$`)

type entry struct {
	English string // 英文关键字，必须与 scanner.go 的 textToKeyword 左侧完全一致
	Kind    string // scanner.go 中对应的 ast.Kind 名字
	Chinese string // 汉语译名
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "genzhkeywords: "+format+"\n", args...)
	os.Exit(1)
}

// parseScannerKeywords 解析 scanner.go 的 textToKeyword，返回 英文 -> Kind名。
func parseScannerKeywords() map[string]string {
	data, err := os.ReadFile(scannerPath)
	if err != nil {
		fatal("读不到 %s：%v", scannerPath, err)
	}
	result := map[string]string{}
	inTable := false
	for _, line := range strings.Split(string(data), "\n") {
		if strings.Contains(line, "textToKeyword = map[string]ast.Kind{") {
			inTable = true
			continue
		}
		if !inTable {
			continue
		}
		if strings.HasPrefix(strings.TrimSpace(line), "}") {
			break
		}
		if m := keywordEntryRe.FindStringSubmatch(line); m != nil {
			result[m[1]] = m[2]
		}
	}
	if len(result) == 0 {
		fatal("没能从 %s 解出任何 textToKeyword 条目（扫描器结构变了？）", scannerPath)
	}
	return result
}

// hanCount 数出一个字符串里的汉字个数（按汉字算，不按字节或总字符算）。
func hanCount(s string) int {
	n := 0
	for _, r := range s {
		if unicode.Is(unicode.Han, r) {
			n++
		}
	}
	return n
}

func parseWordList() []entry {
	data, err := os.ReadFile(wordListPath)
	if err != nil {
		fatal("读不到 %s：%v", wordListPath, err)
	}
	if !utf8.Valid(data) {
		fatal("%s 不是合法 UTF-8", wordListPath)
	}
	scannerKinds := parseScannerKeywords()

	var entries []entry
	seenEn := map[string]bool{}
	seenZh := map[string]string{}
	lineNo := 0
	for _, raw := range strings.Split(string(data), "\n") {
		lineNo++
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 2 {
			fatal("%s:%d 格式应为「<英文关键字> <中文译名>」，实际为 %q", wordListPath, lineNo, line)
		}
		en, zh := fields[0], fields[1]
		kind, ok := scannerKinds[en]
		if !ok {
			fatal("%s:%d 英文关键字 %q 不在 scanner.go 的 textToKeyword 里", wordListPath, lineNo, en)
		}
		if seenEn[en] {
			fatal("%s:%d 英文关键字 %q 重复", wordListPath, lineNo, en)
		}
		if prev, dup := seenZh[zh]; dup {
			fatal("%s:%d 译名 %q 重复（已被 %q 使用）—— 译名必须唯一", wordListPath, lineNo, zh, prev)
		}
		if n := hanCount(zh); n < 2 || n > 6 {
			fatal("%s:%d 译名 %q 有 %d 个汉字，违反定则（必须 2..6 个汉字）", wordListPath, lineNo, zh, n)
		}
		if strings.ContainsAny(zh, " \t") {
			fatal("%s:%d 译名 %q 含空白字符", wordListPath, lineNo, zh)
		}
		seenEn[en] = true
		seenZh[zh] = en
		entries = append(entries, entry{English: en, Kind: kind, Chinese: zh})
	}

	// 覆盖率：扫描器里每个英文关键字都必须有译名，否则就是「漏译」。
	var missing []string
	for en := range scannerKinds {
		if !seenEn[en] {
			missing = append(missing, en)
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		fatal("%s 漏译 %d 个英文关键字：%s", wordListPath, len(missing), strings.Join(missing, " "))
	}

	sort.Slice(entries, func(i, j int) bool { return entries[i].English < entries[j].English })
	return entries
}

func render(entries []entry) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by tsc/cmd/genzhkeywords from zh_keywords.txt. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// ChineseTypeScript 汉语关键字别名表（Chinese keyword aliases）。\n")
	b.WriteString("//\n")
	b.WriteString("// 效果：汉语拼写与英文拼写被识别为同一个关键字。例如\n")
	b.WriteString("//\n")
	b.WriteString("//\t汉语 `如果`  ─┐\n")
	b.WriteString("//\t               ├─→  ast.KindIfKeyword\n")
	b.WriteString("//\t英文 `if`    ─┘\n")
	b.WriteString("//\n")
	b.WriteString("// 【不变式·必须遵守】本表是【独立】的，绝不可并入 textToKeyword / textToToken。\n")
	b.WriteString("// 理由（有据，非推测）：scanner.go 的 tokenToText 由 textToToken 倒排而来 ——\n")
	b.WriteString("//\n")
	b.WriteString("//\tfor text, kind := range textToToken { result[kind] = text }\n")
	b.WriteString("//\n")
	b.WriteString("// 而 Go 的 map 遍历顺序是随机的。中文键一旦混入，tokenToText[ast.KindIfKeyword]\n")
	b.WriteString("// 会在 \"if\" 与 \"如果\" 之间【随机】取值，printer 的 writeTokenText 又直接用它\n")
	b.WriteString("// 落盘，于是生成的 js 会不确定地含中文关键字 —— 那是非法 JS。\n")
	b.WriteString("//\n")
	b.WriteString("// 守卫 tsc/internal/scanner/zh_keywords_test.go 会机器校核这条不变式。\n")
	b.WriteString("//\n")
	b.WriteString("// 单一真源：tsc/internal/scanner/zh_keywords.txt（本文件由它生成，勿手改）。\n")
	b.WriteString("\n")
	b.WriteString("package scanner\n")
	b.WriteString("\n")
	b.WriteString("import \"github.com/microsoft/TypeScript/tsc/internal/ast\"\n")
	b.WriteString("\n")
	b.WriteString("// zhTextToKeyword 把汉语关键字拼写映射到与英文【完全相同】的关键字种类。\n")
	b.WriteString("// 因此词法分析之后的一切（parser / binder / checker / printer / ls）都无需改动。\n")
	b.WriteString("var zhTextToKeyword = map[string]ast.Kind{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%q: ast.Kind%s,\n", e.Chinese, e.Kind)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func main() {
	check := flag.Bool("check", false, "只校验生成物是否与词表一致，不写盘")
	flag.Parse()

	entries := parseWordList()
	raw := render(entries)
	formatted, err := format.Source(raw)
	if err != nil {
		fatal("生成的源码不是合法 Go：%v\n%s", err, raw)
	}

	if *check {
		existing, err := os.ReadFile(outputPath)
		if err != nil {
			fatal("%s 不存在，请先运行 go run ./cmd/genzhkeywords", outputPath)
		}
		if !bytes.Equal(existing, formatted) {
			fatal("%s 与 %s 不一致，请运行 go run ./cmd/genzhkeywords", outputPath, wordListPath)
		}
		fmt.Printf("genzhkeywords: %s 与 %s 一致（%d 条译名）\n", outputPath, wordListPath, len(entries))
		return
	}

	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		fatal("建目录失败：%v", err)
	}
	if err := os.WriteFile(outputPath, formatted, 0o644); err != nil {
		fatal("写 %s 失败：%v", outputPath, err)
	}
	fmt.Printf("genzhkeywords: 已生成 %s（%d 条译名）\n", outputPath, len(entries))
}
